#!/bin/sh
# Writes /usr/share/nginx/html/config.js from env at container start, then
# execs nginx. One image, three modes:
#   APP_MODE=portal (default) | invoice-admin | invoice-client
#   DEMO_MODE=true|false      — shows demo hints (buyer confirm link, OTP echo)
#   PUBLIC_VERIFY_BASE=https://host — origin used for verify links / QR codes
set -eu

HTML_ROOT="${HTML_ROOT:-/usr/share/nginx/html}"
APP_MODE="${APP_MODE:-portal}"
DEMO_MODE="${DEMO_MODE:-false}"
PUBLIC_VERIFY_BASE="${PUBLIC_VERIFY_BASE:-}"

case "$APP_MODE" in
  portal|invoice-admin|invoice-client) ;;
  *) echo "docker-entrypoint: unknown APP_MODE '$APP_MODE', falling back to 'portal'" >&2; APP_MODE=portal ;;
esac

case "$(printf '%s' "$DEMO_MODE" | tr '[:upper:]' '[:lower:]')" in
  1|true|yes|on) DEMO_MODE=true ;;
  *) DEMO_MODE=false ;;
esac

# Escape characters that would break a JS double-quoted string.
js_escape() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

cat > "$HTML_ROOT/config.js" <<EOF
// Generated by docker-entrypoint.sh — do not edit inside the container.
window.__NEMO_CONFIG__ = {
  mode: "$(js_escape "$APP_MODE")",
  demo: ${DEMO_MODE},
  publicVerifyBase: "$(js_escape "$PUBLIC_VERIFY_BASE")",
};
EOF

echo "docker-entrypoint: APP_MODE=$APP_MODE DEMO_MODE=$DEMO_MODE PUBLIC_VERIFY_BASE=${PUBLIC_VERIFY_BASE:-<same-origin>}"

if [ "$#" -eq 0 ]; then
  set -- nginx -g 'daemon off;'
fi
exec "$@"
